const DICTS: Record<Lang, Record<MessageKey, string>> = { en, es };

export function isLang(v: unknown): v is Lang {
  return v === "en" || v === "es";
}

export function t(lang: Lang, key: MessageKey, vars: Record<string, string | number> = {}): string {
  const template = DICTS[lang][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export const LANGUAGE_NAMES: Record<Lang, Record<string, string>> = {
  en: { en: "English", es: "Spanish", vi: "Vietnamese", ar: "Arabic", am: "Amharic", fr: "French", ru: "Russian", zh: "Chinese" },
  es: { en: "inglés", es: "español", vi: "vietnamita", ar: "árabe", am: "amárico", fr: "francés", ru: "ruso", zh: "chino" },
};

export function languageName(lang: Lang, code: string): string {
  return LANGUAGE_NAMES[lang][code] ?? code;
}

/** Client-side strings needed by public/saved.js. */
export function clientMessages(lang: Lang): Record<string, string> {
  const keys = (Object.keys(en) as MessageKey[]).filter((k) => k.startsWith("saved.") || k.startsWith("consent.") || k.startsWith("detail.save") || k === "detail.call");
  return Object.fromEntries(keys.map((k) => [k, DICTS[lang][k]]));
}
